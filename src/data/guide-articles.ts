export function getJournalArticle(slug: string) {
  const fullArticle = journalArticles.find((article) => article.slug === slug);
  if (fullArticle) return fullArticle;

  const topic = additionalJournalTopics.find((article) => article.slug === slug);
  if (!topic) return undefined;

  const content = additionalArticleContent[topic.slug];
  if (!content) return undefined;

  return {
    ...topic,
    readTime: "4 min read",
    intro: content.intro,
    sections: content.sections,
    related: content.related,
  };
}
